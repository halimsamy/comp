import { renderIsmsPdf } from '../../isms/utils/pdf-renderer';
import type { NativeEvidenceRule, RuleResult } from './native-evidence.types';
import { formatDate } from './native-evidence.types';

/**
 * Dated snapshot of the native state that satisfies a task, for the auditor.
 * A snapshot, not a controlled document: no version, draft status or next
 * review (#43); the header says when and from where it was generated.
 */
export function renderNativeEvidencePdf({
  rule,
  result,
  taskTitle,
  organizationName,
  primaryColor,
  reviewerName = null,
  now,
}: {
  rule: NativeEvidenceRule;
  result: RuleResult;
  taskTitle: string;
  organizationName: string | null;
  primaryColor: string | null;
  reviewerName?: string | null;
  now: Date;
}): { buffer: Buffer; filename: string } {
  const documentCode = `AE-${result.fingerprint.slice(0, 8).toUpperCase()}`;
  const generatedAt = `${now.toISOString().slice(0, 16).replace('T', ' ')} UTC`;
  const buffer = renderIsmsPdf({
    sections: [
      {
        heading: 'Evidence summary',
        intro: `Generated by Comp AI from the ${rule.module} module. It shows the records as they were at that moment; a person reviews it before the task is completed.`,
        keyValues: [
          { label: 'Rule', value: rule.title },
          { label: 'Summary', value: result.summary },
          { label: 'Requirements', value: rule.reference },
        ],
      },
      ...result.sections,
    ],
    metadata: {
      title: taskTitle,
      clause: rule.reference,
      documentCode,
      standardLabel: 'Auto-evidence snapshot',
      frameworkName: 'ISO 27001',
      version: 1,
      preparedBy: 'Comp AI',
      owner: null,
      status: null,
      approverName: null,
      approvedAt: null,
      declinedAt: null,
      classification: 'Confidential',
      nextReview: '',
      issueDate: now,
      organizationName,
      primaryColor,
      rows: [
        { label: 'Snapshot ID', value: documentCode },
        { label: 'Task', value: taskTitle },
        { label: 'Generated at', value: generatedAt },
        { label: 'Generated from', value: `${rule.module} module (${rule.path})` },
        { label: 'Rule result', value: result.holds ? 'Met' : 'Not met' },
        { label: 'Reviewer', value: reviewerName ?? 'Assigned when sent for review' },
        { label: 'Approved on', value: 'Recorded on the task when the reviewer approves it' },
        { label: 'Classification', value: 'Confidential' },
      ],
    },
  });
  const slug = taskTitle.replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase();
  return { buffer, filename: `${slug || 'task'}-evidence-${formatDate(now)}.pdf` };
}
